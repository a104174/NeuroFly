const authority=parseNeuralLocomotion(JSON.parse(readFileSync(new URL('../public/experiments/experimental_locomotion_v1.json',import.meta.url),'utf8')));
test('actual walking, exact handoffs, one native integrator per global interval and deterministic complete mixed evidence',async()=>{
 const a=runMixedGroundFlight(authority), b=runMixedGroundFlight(authority);
 assert.equal(a.termination,'SECOND_FLIGHT_CONFIRMED',a.failure??'');
 assert.equal(flightCanonical(a),flightCanonical(b));assert.equal(await mixedGroundFlightHash(a),await mixedGroundFlightHash(b));
 assert.equal(a.handoffs.length,2);
 assert(a.metrics.walking_distance_units>=.05);assert(a.metrics.walking_duration_s>0);
 assert.equal(a.metrics.maximum_handoff_position_discontinuity,0);assert.equal(a.metrics.maximum_timestamp_discontinuity,0);
 assert.equal(a.metrics.accepted_bound_violations,0);assert.equal(a.metrics.invalid_command_count,0);
 assert.notDeepEqual(a.handoffs[0].position,a.handoffs[1].position);
 const walking=a.intervals.filter(i=>i.active_engine==='ground');
 const independent=new LiveGroundSession(authority,true,'independent',undefined,{position:a.handoffs[0].position,heading:a.handoffs[0].heading});independent.start();
 assert(independent.snapshot().hs.every(v=>v===0));assert(independent.snapshot().dn.every(v=>v===0));
 assert.deepEqual(a.handoffs[0].neural_initialization,{hs:[0,0,0,0,0,0],dn:[0,0],first_observation:null});
 for(const interval of walking)assert.deepEqual(interval.native_evidence,independent.advance());
 assert.equal((walking[0].native_evidence as LiveSample).interval.sensory_summary,null);
 assert.equal((walking[1].native_evidence as LiveSample).interval.sensory_summary?.before_step,0);
 assert.equal((walking[1].native_evidence as LiveSample).interval.sensory_summary?.available_step,1);
 assert.deepEqual(walking.at(-1)!.accepted.position,a.handoffs[1].position);
 let previous=a.initial;
 for(const i of a.intervals){
   assert.equal(i.global_step,previous.step);assert.equal(i.global_time_s,previous.time);
   assert.equal(i.accepted.step,previous.step+1);assert.equal(i.accepted.time,i.accepted.step*.02);
   assert.deepEqual(i.observation.accepted,previous);
   i.accepted.position.forEach((v,axis)=>assert(Math.abs(v-previous.position[axis])<=.18*.02+1e-10));
   assert([...i.accepted.position,...i.accepted.velocity,i.accepted.heading].every(Number.isFinite));
   previous=i.accepted;
 }
 const second=a.intervals.find(i=>i.active_engine==='flight_resumed')!;
 assert.deepEqual(second.observation.accepted.position,a.handoffs[1].position);
 const native=second.native_evidence as {observation:{accepted:{position:number[];velocity:number[]}}};
 assert.deepEqual(native.observation.accepted.position,a.handoffs[1].position);
 assert.deepEqual(native.observation.accepted.velocity,a.handoffs[1].velocity);
 assert.equal(a.metrics.transitions.filter(e=>e.detail==='grounded->takeoff').length,2);
});
test('handoff predicates reject unsafe contacts, collision envelopes and insufficient walking at the same boundary',async()=>{
 const r=runMixedGroundFlight(authority), landed=r.intervals.find(i=>i.accepted.contacts.includes('FLOOR'))!.accepted;
 assert.deepEqual(validateLandingHandoff(landed,authority).position,landed.position);
 assert.throws(()=>validateLandingHandoff({...landed,state:'landing'},authority),/handoff/);
 assert.throws(()=>validateLandingHandoff({...landed,contacts:[]},authority),/handoff/);
 assert.throws(()=>validateLandingHandoff({...landed,position:[2,landed.position[1],0]},authority),/handoff/);
 const end=r.intervals.filter(i=>i.active_engine==='ground').at(-1)!.accepted;
 assert.equal(walkingTakeoffEligible(.01,end),false);assert.equal(walkingTakeoffEligible(.05,end),true);
 assert.equal(walkingTakeoffEligible(.05,{...end,position:[.913,end.position[1],0],heading:Math.PI/2}),false);
 const engine=new FlightEngine(createFlightTrial([],40),FLIGHT_MODEL.arena,{position:[...end.position],heading:end.heading,velocity:[...end.velocity]});
 assert.deepEqual(engine.snapshot().position,end.position);assert.deepEqual(engine.snapshot().velocity,end.velocity);
 await assert.rejects(()=>exportFlight(engine,'normal'));
 assert.throws(()=>new FlightEngine(createFlightTrial([],40),FLIGHT_MODEL.arena,{position:[0,1,0],heading:0,velocity:[0,0,0]}),/handoff/);
});
test('pause/reset ownership and UI option preserve existing modes and map genuine walking to leg presentation',()=>{
 const s=new MixedGroundFlightSession(authority);s.start();const clock=new FlightClock();clock.advance(s,100);s.pause();const old=s.snapshot();
 assert.throws(()=>s.advance(),/not running/);assert.deepEqual(s.snapshot(),old);s.start();clock.reset();clock.advance(s,20);assert.equal(s.snapshot().step,old.step+1);
 s.dispose();assert.throws(()=>s.advance(),/not running/);
 assert.equal(createReactiveFlightLabSession('mixed',authority).snapshot().step,0);
 const markup=renderToStaticMarkup(createElement(ReactiveFlightExplorationLab,{modeControl:null,authority}));
 assert.match(markup,/Flight \+ ground exploration/);assert.match(markup,/aria-pressed="true">Continuous exploration/);
 const selected=renderToStaticMarkup(createElement(ReactiveFlightSessionLab,{modeControl:null,behavior:'mixed',authority}));
 assert.match(selected,/mixed_ground_flight_v1/);assert.match(selected,/fresh ground neural episodes/);
 const walk=new MixedGroundFlightSession(authority);walk.start();while(walk.controllerPhase!=='walking')walk.advance();walk.advance();
 const samples=walk.presentationBodySamples();assert(samples.length>=2);assert.notDeepEqual(samples[0].position,samples.at(-1)!.position);
});
